import { screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { http, HttpResponse } from "msw";
import { axe } from "vitest-axe";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { UNIT, report } from "@/test/fixtures";
import { API, USERS, renderApp, signInAs } from "@/test/render";
import { server } from "@/test/server";

const SLOW = { timeout: 8000 };

/** Serve every report, remembering each request's address. */
function serveReports(body = report()) {
  const seen: URL[] = [];
  server.use(
    http.get(`${API}/reports/:name`, ({ request }) => {
      seen.push(new globalThis.URL(request.url));
      return HttpResponse.json(body);
    }),
    http.get(`${API}/units`, () =>
      HttpResponse.json({
        items: [{ ...UNIT, is_active: true }],
        total: 1,
        page: 1,
        page_size: 100,
      }),
    ),
  );
  return seen;
}

describe("viewing a report", () => {
  it("shows the summary, the tables and the totals, with no accessibility violations", async () => {
    signInAs(USERS.admin);
    serveReports();
    const view = renderApp("/reports?report=turnaround");
    expect(await screen.findByRole("article", { name: "Repair turnaround" }, SLOW)).toBeVisible();

    const summary = screen.getByLabelText("Summary");
    expect(within(summary).getByText("Repairs returned")).toBeVisible();
    expect(within(summary).getByText("4.5")).toBeVisible();

    const row = screen.getByRole("row", { name: /Registration Office/ });
    expect(within(row).getByText("4.3")).toBeVisible();
    expect(screen.getByRole("row", { name: /All units/ })).toBeVisible(); // the totals row
    expect(screen.getByText("Days from intake to return.")).toBeVisible();
    expect(screen.getByText("Generated by:")).toBeVisible();
    expect(await axe(view.container)).toHaveNoViolations();
  });

  it("shows datetimes and dates the Lagos way, and identifiers as identifiers", async () => {
    signInAs(USERS.admin);
    serveReports();
    renderApp("/reports?report=turnaround");
    const row = await screen.findByRole("row", { name: /LAS-ENG-000002/ }, SLOW);
    expect(within(row).getByText("05 Oct 2026, 14:30")).toBeVisible();
    expect(within(row).getByText("05 Oct 2026")).toBeVisible();
    expect(within(row).getByText("LAS-ENG-000002")).toHaveClass("mono");
  });

  it("says when a section has nothing to report", async () => {
    signInAs(USERS.admin);
    const empty = report();
    empty.sections = [{ ...empty.sections[0]!, rows: [], totals: null }];
    serveReports(empty);
    renderApp("/reports?report=turnaround");
    expect(
      await screen.findByText("Nothing to report for this period.", undefined, SLOW),
    ).toBeVisible();
  });
});

describe("report settings", () => {
  it("asks the server for exactly the settings in the address", async () => {
    signInAs(USERS.admin);
    const seen = serveReports();
    renderApp(`/reports?report=repeat-faults&from=2026-08-01&to=2026-10-31&min=4&unit=${UNIT.id}`);
    await screen.findByRole("article", undefined, SLOW);
    const last = seen.at(-1)!;
    expect(last.pathname).toBe("/api/v1/reports/repeat-faults");
    expect(Object.fromEntries(last.searchParams)).toEqual({
      from: "2026-08-01",
      to: "2026-10-31",
      min: "4",
      unit_id: UNIT.id,
    });
  });

  it("opens on this month's activity when nothing is chosen", async () => {
    signInAs(USERS.admin);
    const seen = serveReports();
    renderApp("/reports");
    await screen.findByRole("article", undefined, SLOW);
    expect(seen.at(-1)!.pathname).toBe("/api/v1/reports/monthly-activity");
    expect(seen.at(-1)!.searchParams.get("month")).toMatch(/^\d{4}-\d{2}$/);
  });

  it("switches report from the picker and offers only that report's settings", async () => {
    signInAs(USERS.admin);
    const seen = serveReports();
    renderApp("/reports?report=turnaround");
    await screen.findByRole("article", undefined, SLOW);
    expect(screen.getByLabelText("From")).toBeVisible();
    expect(screen.queryByLabelText("Month")).not.toBeInTheDocument();

    await userEvent.click(screen.getByRole("link", { name: "Open tickets" }));
    await waitFor(() => expect(seen.at(-1)!.pathname).toBe("/api/v1/reports/open-tickets"));
    expect(screen.queryByLabelText("From")).not.toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Open tickets" })).toHaveAttribute(
      "aria-current",
      "page",
    );
  });

  it("does not ask the server for a month that is not a month", async () => {
    signInAs(USERS.admin);
    const seen = serveReports();
    renderApp("/reports?report=monthly-activity&month=oops");
    expect(await screen.findByText(/Check the settings above/, undefined, SLOW)).toBeVisible();
    expect(seen).toEqual([]);
    expect(screen.getByRole("button", { name: "Excel" })).toBeDisabled();
  });

  it("explains the server's refusal of a bad period in plain words", async () => {
    signInAs(USERS.admin);
    server.use(
      http.get(`${API}/reports/turnaround`, () =>
        HttpResponse.json(
          { error: { code: "INVALID_RANGE", message: "from must not be after to" } },
          { status: 422 },
        ),
      ),
      http.get(`${API}/units`, () =>
        HttpResponse.json({ items: [], total: 0, page: 1, page_size: 100 }),
      ),
    );
    renderApp("/reports?report=turnaround&from=2026-10-31&to=2026-08-01");
    expect(
      await screen.findByText("The start date must not be after the end date.", undefined, SLOW),
    ).toBeVisible();
  });

  it("gives a unit representative no unit filter, and ignores a unit typed into the address", async () => {
    signInAs(USERS.rep);
    const seen = serveReports();
    renderApp("/reports?report=open-tickets&unit=99999999-9999-4999-8999-999999999999");
    await screen.findByRole("article", undefined, SLOW);
    expect(screen.queryByLabelText("Unit")).not.toBeInTheDocument();
    expect(seen.at(-1)!.searchParams.has("unit_id")).toBe(false);
    // Nothing to set on this report for a rep, so no empty settings box either.
    expect(screen.queryByRole("search", { name: "Report settings" })).not.toBeInTheDocument();
  });
});

describe("printing and downloading", () => {
  let created: Blob[] = [];
  let clicked: Array<{ download: string }> = [];

  beforeEach(() => {
    created = [];
    clicked = [];
    URL.createObjectURL = (blob: Blob | MediaSource) => {
      created.push(blob as Blob);
      return "blob:test";
    };
    URL.revokeObjectURL = () => {};
    vi.spyOn(HTMLAnchorElement.prototype, "click").mockImplementation(function (
      this: HTMLAnchorElement,
    ) {
      clicked.push({ download: this.download });
    });
  });
  afterEach(() => vi.restoreAllMocks());

  it("opens the print dialog from the Print button", async () => {
    signInAs(USERS.admin);
    serveReports();
    const print = vi.spyOn(window, "print").mockImplementation(() => {});
    renderApp("/reports?report=turnaround");
    const button = await screen.findByRole("button", { name: "Print" }, SLOW);
    await waitFor(() => expect(button).toBeEnabled());
    await userEvent.click(button);
    expect(print).toHaveBeenCalledTimes(1);
  });

  it("lets the head of engineering, an engineer and a rep all print", async () => {
    for (const who of [USERS.admin, USERS.engineer, USERS.rep]) {
      signInAs(who);
      serveReports();
      const view = renderApp("/reports?report=turnaround");
      const button = await screen.findByRole("button", { name: "Print" }, SLOW);
      await waitFor(() => expect(button).toBeEnabled());
      view.unmount();
    }
  });

  it("downloads Excel through the signed-in client and saves it under the server's file name", async () => {
    signInAs(USERS.admin);
    serveReports();
    let auth: string | null = null;
    let format: string | null = null;
    server.use(
      http.get(`${API}/reports/turnaround`, ({ request }) => {
        const url = new globalThis.URL(request.url);
        if (url.searchParams.get("format") !== "xlsx") return HttpResponse.json(report());
        auth = request.headers.get("authorization");
        format = url.searchParams.get("format");
        return new HttpResponse("xlsx-bytes", {
          headers: {
            "content-type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            "content-disposition": 'attachment; filename="repair-turnaround-2026-11.xlsx"',
          },
        });
      }),
    );
    renderApp("/reports?report=turnaround");
    const excel = await screen.findByRole("button", { name: "Excel" }, SLOW);
    await waitFor(() => expect(excel).toBeEnabled());
    await userEvent.click(excel);

    await waitFor(() => expect(clicked).toEqual([{ download: "repair-turnaround-2026-11.xlsx" }]));
    expect(format).toBe("xlsx");
    expect(auth).toBe("Bearer test-token");
    expect(created).toHaveLength(1);
    expect(await screen.findByText("Download started")).toBeVisible();
  });

  it("asks for a PDF with the same settings as the screen", async () => {
    signInAs(USERS.admin);
    const seen = serveReports();
    renderApp("/reports?report=turnaround&from=2026-08-01&to=2026-10-31");
    const pdf = await screen.findByRole("button", { name: "PDF" }, SLOW);
    await waitFor(() => expect(pdf).toBeEnabled());
    await userEvent.click(pdf);
    await waitFor(() =>
      expect(seen.some((u) => u.searchParams.get("format") === "pdf")).toBe(true),
    );
    const request = seen.find((u) => u.searchParams.get("format") === "pdf")!;
    expect(request.searchParams.get("from")).toBe("2026-08-01");
    expect(request.searchParams.get("to")).toBe("2026-10-31");
  });

  it("tells the person when a download fails, and saves nothing", async () => {
    signInAs(USERS.admin);
    server.use(
      http.get(`${API}/reports/turnaround`, ({ request }) =>
        new globalThis.URL(request.url).searchParams.has("format")
          ? HttpResponse.json(
              { error: { code: "RANGE_TOO_LARGE", message: "too big" } },
              { status: 422 },
            )
          : HttpResponse.json(report()),
      ),
      http.get(`${API}/units`, () =>
        HttpResponse.json({ items: [], total: 0, page: 1, page_size: 100 }),
      ),
    );
    renderApp("/reports?report=turnaround");
    const excel = await screen.findByRole("button", { name: "Excel" }, SLOW);
    await waitFor(() => expect(excel).toBeEnabled());
    await userEvent.click(excel);
    expect(await screen.findByText("Could not download")).toBeVisible();
    expect(screen.getByText("Choose a period of five years or less.")).toBeVisible();
    expect(clicked).toEqual([]);
  });
});
