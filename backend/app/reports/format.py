"""How report values are shown to people, shared by the Excel and PDF renderers."""

import re
from datetime import date, datetime
from typing import Any

from app.core.timeutil import APP_TIMEZONE
from app.schemas.reports import Report

DATE_FORMAT = "%d %b %Y"
DATETIME_FORMAT = "%d %b %Y %H:%M"


def display(value: Any, type_: str) -> str:
    """The text a person sees for one cell."""
    if value is None or value == "":
        return ""
    if type_ == "number":
        return f"{value:.1f}"
    if type_ == "date":
        return date.fromisoformat(value).strftime(DATE_FORMAT)
    if type_ == "datetime":
        return datetime.fromisoformat(value).strftime(DATETIME_FORMAT)
    return str(value)


def summary_display(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:.1f}"
    return "" if value is None else str(value)


def footer_text(report: Report) -> str:
    when = report.generated_at.astimezone(APP_TIMEZONE)
    return f"Generated by {report.generated_by.full_name} on {when:%d %b %Y %H:%M} (Africa/Lagos)"


def headline(report: Report) -> list[str]:
    return [report.title, report.period, f"Scope: {report.scope.label}"]


def filename(report: Report, extension: str) -> str:
    """lasrra-monthly-activity-october-2026.xlsx (snapshot reports carry the date instead)."""
    if report.period.startswith("As at"):
        label = report.generated_at.astimezone(APP_TIMEZONE).strftime("%Y-%m-%d")
    else:
        label = re.sub(r"[^a-z0-9]+", "-", report.period.lower()).strip("-")
    return f"lasrra-{report.key}-{label}.{extension}"
