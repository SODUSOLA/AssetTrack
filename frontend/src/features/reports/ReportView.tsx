import type { Report, Section } from "@/api/types";
import { DataTable, type Column } from "@/components/ui/DataTable";
import { Panel } from "@/components/ui/Panel";
import { formatDateTime } from "@/lib/format";
import { formatCell, formatFigure, isNumeric } from "@/lib/reports";
import s from "./ReportView.module.css";

type Row = Record<string, unknown>;

const IDENTIFIERS = new Set(["asset_tag", "ticket_no"]);

function columnsOf(section: Section): Column<Row>[] {
  return section.columns.map((column, index) => ({
    id: column.key,
    header: column.label,
    primary: index === 0,
    ...(isNumeric(column.type ?? "text") ? { align: "right" as const } : {}),
    cell: (row) => {
      const text = formatCell(row[column.key], column.type ?? "text");
      if (IDENTIFIERS.has(column.key)) return <span className="mono">{text}</span>;
      return isNumeric(column.type ?? "text") ? <span className={s.num}>{text}</span> : text;
    },
  }));
}

function SectionTable({ section }: { section: Section }) {
  const columns = columnsOf(section);
  const totals = section.totals
    ? Object.fromEntries(
        section.columns.map((column) => [
          column.key,
          formatCell(section.totals?.[column.key], column.type ?? "text"),
        ]),
      )
    : undefined;
  // Wide reports need room: switch to cards when the table is narrower than its columns want.
  const cardsBelow = Math.max(640, columns.length * 115);
  return (
    <Panel title={section.title} flush className={s.section}>
      {section.rows.length === 0 ? (
        <p className={s.empty}>Nothing to report for this period.</p>
      ) : (
        <DataTable
          caption={section.title}
          columns={columns}
          rows={section.rows as Row[]}
          rowKey={(_, index) => index}
          cardsBelow={cardsBelow}
          totals={totals}
        />
      )}
      {section.note && <p className={s.note}>{section.note}</p>}
    </Panel>
  );
}

/**
 * Any report, drawn from the one generic shape every report has. Nothing here knows which
 * report it is showing, so a new report in the API appears without a new screen.
 */
export function ReportView({ report }: { report: Report }) {
  return (
    <article aria-label={report.title}>
      <dl className={s.meta}>
        <div>
          <dt>Period:</dt>
          <dd>{report.period}</dd>
        </div>
        <div>
          <dt>For:</dt>
          <dd>{report.scope.label}</dd>
        </div>
        <div>
          <dt>Generated by:</dt>
          <dd>
            {report.generated_by.full_name}, {formatDateTime(report.generated_at)}
          </dd>
        </div>
      </dl>

      <dl className={s.figures} aria-label="Summary">
        {report.summary.map((item) => (
          <div key={item.key} className={s.figure}>
            <dt className={s.figureLabel}>{item.label}</dt>
            <dd className={s.figureValue}>{formatFigure(item.value, item.key)}</dd>
          </div>
        ))}
      </dl>

      <div className={s.sections}>
        {report.sections.map((section) => (
          <SectionTable key={section.key} section={section} />
        ))}
      </div>
    </article>
  );
}
